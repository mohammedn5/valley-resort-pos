// ============================================================
// تطبيع الأرقام (Digit Normalization)
// ============================================================
// المشكلة: في الحقول الرقمية داخل واجهة عربية (dir="rtl", lang="ar")، بعض
// الأجهزة والمتصفحات (خصوصاً iOS بلوحة مفاتيح عربية) تُدخل الأرقام بصيغة
// "الأرقام الهندية الشرقية" (٠١٢٣٤٥٦٧٨٩) بدلاً من الأرقام الإنجليزية، رغم أن
// حقل الإدخال من نوع number. الدالة الأصلية Number("١٢") أو parseInt("١٢")
// تُرجع NaN لأنها لا تتعرف على هذه الرموز، مما يجعل أي تحقق مثل
// `Number(value) > 0` يفشل بصمت حتى لو كانت القيمة المعروضة تبدو صحيحة تماماً
// للمستخدم. هذا هو السبب الجذري لرفض بنود فاتورة الشراء رغم إدخالها فعلياً.
//
// الحل: تطبيع أي نص رقمي إلى أرقام إنجليزية قبل أي عملية تحويل رقمي، وتطبيق
// ذلك مباشرة عند كل onChange حتى تُعرض القيمة المطبَّعة للمستخدم فوراً.

const EASTERN_DIGITS_MAP: Record<string, string> = {
  // الأرقام الهندية الشرقية (العربية)
  "٠": "0",
  "١": "1",
  "٢": "2",
  "٣": "3",
  "٤": "4",
  "٥": "5",
  "٦": "6",
  "٧": "7",
  "٨": "8",
  "٩": "9",
  // الأرقام الفارسية الممتدة
  "۰": "0",
  "۱": "1",
  "۲": "2",
  "۳": "3",
  "۴": "4",
  "۵": "5",
  "۶": "6",
  "۷": "7",
  "۸": "8",
  "۹": "9",
};

/**
 * يحوّل أي أرقام هندية شرقية أو فارسية داخل النص إلى أرقام إنجليزية، ويوحّد
 * الفاصلة العشرية العربية (٫) إلى نقطة، ويزيل فاصل الآلاف العربي (٬).
 */
export function toEnglishDigits(value: string): string {
  return value
    .replace(/[٠-٩۰-۹]/g, (digit) => EASTERN_DIGITS_MAP[digit] ?? digit)
    .replace(/٫/g, ".")
    .replace(/[٬,]/g, "");
}

/** يطبّع النص ثم يحوّله لعدد صحيح. يعيد NaN إن كان النص غير صالح بعد التطبيع. */
export function parseLocalizedInt(value: string): number {
  const normalized = toEnglishDigits(value).trim();
  if (normalized === "") return NaN;
  return parseInt(normalized, 10);
}

/** يطبّع النص ثم يحوّله لعدد عشري. يعيد NaN إن كان النص غير صالح بعد التطبيع. */
export function parseLocalizedFloat(value: string): number {
  const normalized = toEnglishDigits(value).trim();
  if (normalized === "") return NaN;
  return parseFloat(normalized);
}
